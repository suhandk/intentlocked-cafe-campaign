import { test, expect } from "@playwright/test";
import { readFile, writeFile } from "node:fs/promises";
import type { components } from "../lib/api.generated";
type Snapshot = components["schemas"]["DeliverySnapshot"];

test("failed audit recovers; exact review, approval, export and reload remain usable", async ({ page }) => {
  const data = JSON.parse(await readFile("../docs/evidence/approval-browser-fixtures.json", "utf8"));
  let snapshot: Snapshot = data.before;
  let approvals = 0;
  const failed = { id:"audit-browser-failed",campaign_id:data.campaign.id,campaign_revision:data.campaign.revision,kind:"item_audit",status:"failed",mode:"mock",target_id:snapshot.items[0].id,error_code:"CAFE: extraction has invalid or absent evidence",created_at:new Date().toISOString(),updated_at:new Date().toISOString(),elapsed_seconds:0,completed_steps:0,max_steps:1,calls:1,max_calls:3,list_price_estimate_usd:0,unknown_cost_calls:0,notices:[],cache_hits:[] };
  await page.route("**/api/**", async route => {
    const url = new URL(route.request().url());
    const path = url.pathname;
    let body: unknown;
    if (path === "/api/social-profiles") body={version:0,instagram:null,facebook:null,whatsapp:null};
    else if (path.endsWith("/stream/"+data.campaign.id)) return route.fulfill({contentType:"text/event-stream",body:": offline fixture\n\n"});
    if (path.endsWith("/ready")) body=data.health;
    else if (path.endsWith("/cost")) body=data.cost;
    else if (path.endsWith("/traces")) body=[];
    else if (path.endsWith("/campaigns/"+data.campaign.id)) body=data.campaign;
    else if (path.endsWith("/matrix")) body=data.matrix;
    else if (path.endsWith("/delivery")) body=snapshot;
    else if (path.endsWith("/work")) body=route.request().method()==="POST" ? failed : {jobs:[],active:0,queued:0,concurrency_limit:2,mode:"mock"};
    else if (path.endsWith("/assets")) body={backgrounds:[],posters:[],logos:[]};
    else if (path.endsWith("/approve")) {
      const request=route.request().postDataJSON();
      expect(request.item_ids).toEqual([snapshot.items[0].id]);
      expect(request.observed_hashes[snapshot.items[0].id]).toBe(snapshot.items[0].snapshot_hash);
      expect(request.acknowledged_warning_ids).toContain("r7_promise_0");
      approvals++; snapshot=data.approved; body=data.approval;
    } else if (path.endsWith("/export")) body=data.pack;
    else return route.fulfill({status:404,json:{message:"Offline route unavailable"}});
    return route.fulfill({json:body});
  });
  await page.goto(`/?campaign=${data.campaign.id}#approve-export`);
  const panel=page.getByRole("region",{name:"Approve and export"});
  await panel.getByRole("button",{name:"Audit this item"}).click();
  await expect(page.getByRole("alert").filter({hasText:"audit-browser-failed"})).toBeVisible();
  snapshot=structuredClone(data.after);
  snapshot.items[0].warnings=["G14","r7_promise_0"];
  snapshot.items[0].audit_findings=["Review other customer promise: sample invitation needs owner review."];
  await page.evaluate(campaign=>window.dispatchEvent(new CustomEvent("workflow-update",{detail:{campaign}})),data.campaign.id);
  await expect(page.getByRole("alert").filter({hasText:"audit-browser-failed"})).toHaveCount(0);
  await expect(panel.getByText(/sample invitation needs owner review/)).toBeVisible();
  await panel.getByRole("checkbox").first().check();
  const approve=panel.getByRole("button",{name:"Approve selected items"});
  await expect(approve).toBeDisabled();
  await panel.getByLabel("I acknowledge review warning: G14").check();
  await panel.getByLabel("I acknowledge review warning: r7_promise_0").check();
  await panel.getByLabel("I approve the exact selected current content and poster bytes.").check();
  await expect(approve).toBeEnabled();
  const changed=structuredClone(snapshot);
  changed.items[0].audit_id="new-audit-proof";
  snapshot=changed;
  await page.evaluate(campaign=>window.dispatchEvent(new CustomEvent("workflow-update",{detail:{campaign}})),data.campaign.id);
  await expect(panel.getByLabel("I approve the exact selected current content and poster bytes.")).not.toBeChecked();
  await expect(approve).toBeDisabled();
  for (const warning of ["G14","r7_promise_0"]) await panel.getByLabel(`I acknowledge review warning: ${warning}`).check();
  await panel.getByLabel("I approve the exact selected current content and poster bytes.").check();
  await approve.click();
  await expect(panel.getByText(/Owner approval recorded/)).toBeVisible();
  await expect(panel.getByRole("link",{name:"Download approved text"})).toBeVisible();
  await panel.getByRole("button",{name:"Authorize selected export"}).click();
  await expect(panel.getByRole("link",{name:"Open WhatsApp draft"})).toBeVisible();
  expect(approvals).toBe(1);
  await panel.getByRole("checkbox").first().uncheck();
  await expect(panel.getByRole("link",{name:"Download authorized ZIP and manifest"})).toHaveCount(0);
  await panel.getByRole("button",{name:"Show approved final output"}).click();
  await expect(panel.getByRole("link",{name:"Download authorized ZIP and manifest"})).toBeVisible();
  await page.reload();
  await expect(panel.getByText(/Owner approval recorded/)).toBeVisible();
  await panel.getByRole("button",{name:"Show approved final output"}).click();
  await expect(panel.getByRole("link",{name:"Download authorized ZIP and manifest"})).toBeVisible();
  expect(approvals).toBe(1);
  await expect(page.getByRole("contentinfo").getByRole("button",{name:"Continue"})).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  await panel.screenshot({path:"../docs/evidence/approval-recovery-mobile.png"});
  await writeFile("../docs/evidence/approval-browser-result.json",JSON.stringify({outcome:"PASS",mode:"mock",approval_requests:approvals,old_error_cleared:true,changed_audit_invalidates_review:true,export_and_reload:"PASS",real_campaign_approved:false},null,2));
});
