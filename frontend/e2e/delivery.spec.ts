import { stage } from "./navigation";
import { test, expect } from "@playwright/test";
import { writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import type { components } from "../lib/api.generated";
type Campaign = components["schemas"]["Campaign"];
type Proposal = components["schemas"]["Proposal"];
type Snapshot = components["schemas"]["DeliverySnapshot"];
type Pack = components["schemas"]["ExportPack"];

test("owner diff, forms, atomic publication, approval and authorized export survive reload", async ({ page, request }) => {
  test.setTimeout(240000);
  const root = "http://127.0.0.1:8000/api/campaigns";
  let response = await request.post(root, { data: { languages: ["en"], channels: ["whatsapp"] } });
  expect(response.status()).toBe(201);
  let campaign: Campaign = await response.json();
  const base = `${root}/${campaign.id}`;
  response = await request.post(`${base}/intent`, { data: { expected_revision: campaign.revision, transcript: "Café name: Namma Cafe. Bengaluru. 20 percent off coffee this weekend. Open to all." } });
  expect(response.ok()).toBeTruthy(); campaign = await response.json();
  response = await request.post(`${base}/facts/surface`, { data: { expected_revision: campaign.revision, confirm_canonical: true } });
  expect(response.ok()).toBeTruthy(); campaign = await response.json();
  response = await request.post(`${base}/facts/lock`, { data: { expected_revision: campaign.revision, idempotency_key: crypto.randomUUID(), reviewed_fact_versions: Object.fromEntries(campaign.facts.map((f) => [f.key, f.version])), forms: campaign.facts.filter((f) => f.canonical).map((f) => ({ key: f.key, surface: f.surface })), approve_canonical_and_forms: true, acknowledged_warning_ids: campaign.warnings.map((w) => w.id) } });
  expect(response.ok()).toBeTruthy(); campaign = await response.json();
  response = await request.post(`${base}/strategy`, { data: { expected_revision: campaign.revision } });
  expect(response.ok()).toBeTruthy(); const plan = await response.json();
  response = await request.post(`${base}/generate`, { data: { expected_revision: campaign.revision, strategy_id: plan.id, idempotency_key: crypto.randomUUID(), audience_ids: [plan.hero_audience_id], languages: ["en"], channels: ["whatsapp"] } });
  expect(response.status()).toBe(202);
  await expect.poll(async () => (await (await request.get(`${base}/matrix`)).json()).run.status, { timeout: 90000 }).toBe("completed");
  await page.goto(`/?campaign=${campaign.id}`);
  const changes = page.getByRole("region", { name: "Ledger and changes" });
  const delivery = page.getByRole("region", { name: "Approve and export" });
  await stage(page,"approve-export");
  await expect(delivery.getByText(/created revision .*NOT_RUN/)).toBeVisible();
  await delivery.getByRole("button", { name: "Audit this item" }).click();
  await expect(delivery.getByText(/audit PASS/)).toBeVisible({ timeout: 90000 });
  await delivery.getByRole("checkbox").first().check();
  await delivery.getByLabel("I approve the exact selected current content and poster bytes.").check();
  await delivery.getByRole("button", { name: "Approve selected items" }).click();
  await expect(delivery.getByText("Owner approval recorded", { exact: false })).toBeVisible();
  await delivery.getByRole("button", { name: "Authorize selected export" }).click();
  await expect(delivery.getByRole("link", { name: "Open WhatsApp draft" })).toHaveAttribute("href", /^https:\/\/wa\.me\/\?text=/);
  let before: Snapshot = await (await request.get(`${base}/delivery`)).json();
  const oldItem = before.items[0];
  await stage(page,"ledger-changes");
  await changes.getByLabel("Owner change request").fill("Make it 15%");
  await changes.getByRole("button", { name: "Propose change", exact: true }).click();
  const modal=page.getByRole("dialog",{name:"Confirm the change to locked truth"});
  await expect(modal.getByText("immutable proposal · proposed")).toBeVisible({ timeout: 90000 });
  await modal.screenshot({ path: "../docs/evidence/redesign-regression-regression-b6-owner-diff.png" });
  await modal.getByLabel("I confirm this exact diff and its scope.").check();
  await modal.getByRole("button", { name: "Confirm diff", exact: true }).click();
  await changes.getByRole("button", { name: "Propose changed forms" }).click();
  await expect(changes.getByLabel("Changed OFFER en nom")).toHaveValue("15% off", { timeout: 90000 });
  await changes.getByLabel("I approve the diff and all displayed new forms for publication.").check();
  await changes.getByRole("button", { name: "Publish reviewed revision" }).click();
  await expect(changes.getByText(`Ledger + Changes / Current revision ${campaign.revision + 1}`)).toBeVisible({ timeout: 15000 });
  const forbidden = await request.get(`${base}/export`, { params: { expected_revision: campaign.revision, item_ids: oldItem.id } });
  expect(forbidden.status()).toBe(409);
  await stage(page,"approve-export");
  await expect(delivery.getByText(/audit NOT_RUN/)).toBeVisible();
  expect((await request.get(`${base}/export`, { params: { expected_revision: campaign.revision + 1 } })).status()).toBe(422);
  await delivery.getByRole("button", { name: "Audit this item" }).click();
  await expect(delivery.getByText(/audit PASS/)).toBeVisible({ timeout: 90000 });
  await delivery.getByRole("checkbox").first().check();
  await delivery.getByLabel("I approve the exact selected current content and poster bytes.").check();
  await delivery.getByRole("button", { name: "Approve selected items" }).click();
  await expect(delivery.getByText("Owner approval recorded", { exact: false })).toBeVisible();
  await delivery.getByRole("button", { name: "Authorize selected export" }).click();
  await expect(delivery.getByRole("textbox", { name: "Authorized copy" })).toHaveValue(/15% off/);
  await page.reload();
  await expect(delivery.getByText("Owner approval recorded", { exact: false })).toBeVisible();
  await delivery.getByRole("button", { name: "Render changed square draft" }).click();
  const posterCard = delivery.getByRole("article").filter({ hasText: "poster · pending" });
  await expect(posterCard).toBeVisible({ timeout: 30000 });
  await posterCard.getByRole("button", { name: "Audit this item" }).click();
  await expect(posterCard.getByText(/audit PASS/)).toBeVisible({ timeout: 90000 });
  await posterCard.getByRole("checkbox").check();
  await delivery.getByLabel("I approve the exact selected current content and poster bytes.").check();
  await delivery.getByRole("button", { name: "Approve selected items" }).click();
  await expect(delivery.getByText(/poster · approved/)).toBeVisible();
  await delivery.getByRole("button", { name: "Authorize selected export" }).click();
  const download = delivery.getByRole("link", { name: "Download approved poster separately" });
  await expect(download).toBeVisible();
  const exportedPoster = await request.get(`http://127.0.0.1:8000${await download.getAttribute("href")}`);
  expect(exportedPoster.status()).toBe(200);
  expect(exportedPoster.headers()["x-artifact-approval"]).toBe("approved");
  const png = await exportedPoster.body();
  const authorized: Pack = await (await request.get(`${base}/export`, { params: { expected_revision: campaign.revision + 1 } })).json();
  const file = authorized.files.find((f) => f.artifact_url)!;
  expect(createHash("sha256").update(png).digest("hex")).toBe(file.sha256);
  await writeFile("../docs/evidence/redesign-regression-regression-b6-approved-poster.png", png);
  await stage(page,"ledger-changes");
  await changes.getByLabel("Owner change request").fill("Make it 25%");
  await stage(page,"guardian");
  const redTeam = page.getByRole("region", { name: "Red-Team", exact: true });
  await redTeam.getByRole("button", { name: "Run selected Red-Team mode" }).click();
  await expect(page.getByRole("dialog",{name:"Confirm the change to locked truth"})).toBeVisible({timeout:90000});
  await page.getByRole("dialog").getByRole("button",{name:"Cancel whole proposal"}).click();
  await stage(page,"guardian");
  await redTeam.getByRole("group",{name:"Red-Team mode"}).getByRole("button",{name:"Edit the copy directly"}).click();
  await redTeam.getByRole("button", { name: "Run selected Red-Team mode" }).click();
  await expect(redTeam.getByRole("status")).toContainText("Guardian: BLOCKED");
  await stage(page,"ledger-changes");
  await changes.getByText("Saved proposals, events and version history").click();
  await changes.getByRole("button", { name: `View historical revision ${campaign.revision}` }).click();
  await expect(changes.getByText("Historical snapshot — not current, cannot export as current")).toBeVisible();
  await expect(changes.getByText(`Ledger + Changes / Current revision ${campaign.revision + 1}`)).toBeVisible();
  before = await (await request.get(`${base}/delivery`)).json();
  const current = before.items[0];
  const pack: Pack = await (await request.get(`${base}/export`, { params: { expected_revision: campaign.revision + 1, item_ids: current.id } })).json();
  const proposals: Proposal[] = before.proposals;
  expect(proposals.some((p) => p.status === "published")).toBeTruthy();
  expect(pack.copy_text[current.id]).toContain("15% off");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await stage(page,"approve-export");
  await delivery.screenshot({ path: "../docs/evidence/redesign-regression-regression-b6-delivery-mobile.png" });
  await writeFile("../docs/evidence/redesign-regression-regression-b6-browser-run.json", JSON.stringify({ timestamp: new Date().toISOString(), outcome: "PASS", mode: "mock", live_R8: "NOT_TESTED", native_Kannada_voice: "NOT_TESTED", snapshot: before, authorized_pack: authorized }, null, 2));
});
