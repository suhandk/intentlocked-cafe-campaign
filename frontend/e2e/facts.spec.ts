import { stage } from "./navigation";
import { test, expect } from "@playwright/test";

test("typed clarification, corrected amount, localized review and durable atomic lock", async ({ page }) => {
  test.setTimeout(90000);
  await page.addInitScript(() => {
    Object.defineProperty(window, "SpeechRecognition", { value: undefined });
    Object.defineProperty(window, "webkitSpeechRecognition", { value: undefined });
    Object.defineProperty(window.speechSynthesis, "getVoices", {value: () => []});
  });
  await page.goto("/");
  await page.getByRole("button",{name:"Start a campaign",exact:true}).click();
  await page.getByRole("button", { name: "Use microphone" }).click();
  await expect(page.getByText("Speech input is unavailable in this browser.", { exact: false })).toBeVisible();
  await page.getByLabel("Your brief · review the transcript").fill("I run a café in Bengaluru. fifteen percent off coffee this weekend for students.");
  await page.getByRole("button", { name: "Kannada", exact: true }).last().click();
  await page.getByRole("button", { name: "Kanglish", exact: true }).last().click();
  const intentResponse = page.waitForResponse(response => response.url().endsWith("/work") && response.request().postDataJSON()?.kind === "intent");
  await page.getByRole("button", { name: "Propose facts from transcript", exact: true }).click();
  expect((await intentResponse).ok()).toBeTruthy();
  await expect(page.getByLabel("Café name", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("ID required", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Offer eligibility", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Percent off")).toHaveValue("15");
  await expect(page.getByText("Locked by owner", { exact: true })).toHaveCount(0);
  await page.getByLabel("Café name", { exact: true }).fill("Namma Cafe");
  await page.getByLabel("Percent off").fill("50");
  await page.getByLabel("Offer eligibility", { exact: true }).selectOption("all");
  await page.getByRole("checkbox", { name: /Speech can confuse fifteen and fifty/ }).check();
  await page.getByRole("button", { name: "Save editable facts" }).click();
  await expect(page.getByText("Unsaved fact edits.", { exact: false })).toHaveCount(0);
  await page.getByRole("checkbox", { name: /I confirm the saved canonical facts/ }).check();
  await page.getByRole("button", { name: "Propose localized forms" }).click();
  await expect(page.getByLabel("OFFER en nom", { exact: true })).toHaveValue("50% off", { timeout: 25000 });
  await expect(page.getByLabel("CAFE kn dat", { exact: true })).not.toHaveValue("");
  await expect(page.getByLabel("CAFE kn-Latn loc", { exact: true })).not.toHaveValue("");
  await page.getByRole("button", {name: "Read Kannada forms aloud"}).click();
  await expect(page.getByText("No Kannada voice is installed.", {exact: false})).toBeVisible();
  await page.getByRole("group",{name:"Surface-form language"}).getByRole("button",{name:"English",exact:true}).click();
  await page.getByLabel("CAFE en nom", { exact: true }).fill("Namma Café");
  await page.getByRole("checkbox", { name: /MOCK forms are local test data/ }).check();
  await page.getByRole("checkbox", { name: /Kannada\/Kanglish has not been reviewed/ }).check();
  await page.getByRole("heading", { name: "Approve the words that carry the facts" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "../docs/evidence/redesign-regression-forms-desktop.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("group",{name:"Surface-form language"}).getByRole("button",{name:"Kannada",exact:true}).click();
  await page.getByLabel("CAFE kn nom", { exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: "../docs/evidence/redesign-regression-forms-mobile.png" });
  await page.getByRole("checkbox", { name: /I approve these canonical facts/ }).check();
  const requestPromise = page.waitForRequest((request) => request.url().endsWith("/facts/lock"));
  await page.getByRole("button", { name: "Lock approved facts" }).click();
  const request = await requestPromise;
  await expect(page.getByText("Locked by owner", { exact: true })).toBeVisible();
  await stage(page,"facts-lock");
  const url = page.url();
  const repeated = await page.request.post(request.url(), { data: request.postDataJSON() });
  expect(repeated.status()).toBe(200);
  const snapshot = await repeated.json();
  expect(snapshot.status).toBe("locked");
  expect(snapshot.facts.find((f: { key: string }) => f.key === "ID_RULE").canonical).toBeNull();
  await page.reload();
  await expect(page.getByText("Locked by owner", { exact: true })).toBeVisible();
  await stage(page,"facts-lock");
  await page.getByRole("group",{name:"Fact review section"}).getByRole("button",{name:"Approved wording"}).click();
  await expect(page.getByLabel("CAFE en nom", { exact: true })).toHaveValue("Namma Café");
  await expect(page.getByLabel("Percent off")).toHaveValue("50");
  expect(page.url()).toBe(url);
  await expect(page.getByRole("button", { name: "Lock approved facts" })).toHaveCount(0);
  await page.getByText("Locked by owner", { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "../docs/evidence/redesign-regression-locked-mobile.png" });
});
